local function hash_wrapper(fn, s)
  local a = fn(s)
  local b = fn()
  b = (b + s):digest()
  local c = fn()
  c = c:update(s):digest()

  if c:hex() == b:hex() and b:hex() == c:hex() then
    return a:hex()
  else
    print(string.format("all sha1 hash methods did not match for '%s'", s))
    return false
  end
end

for k,v in pairs(sha1) do
  local res = hash_wrapper(llby.crypto.sha1, k)
  if v ~= res then
    print(string.format("%s did not match (expected sha1) %s, for '%s'", res, v, k))
    return false
  end
end

for k,v in pairs(sha0) do
  local res = hash_wrapper(llby.crypto.sha0, k)
  if v ~= res then
    print(string.format("%s did not match (expected sha0) %s, for '%s'", res, v, k))
    return false
  end
end

return true
